"""Independent fixed native victim vectors; no DUT state generates expectations."""
from copy import deepcopy
import json
from pathlib import Path
import sys


def check(events, seed, topo=None):
    fired = [row for row in events if row["handshake"]]
    base = topo["memoryStart"] if topo else 0x1000
    coherent = next(n["id"] for n in topo["nodes"] if n["kind"] == 0 and n["mode"] != 0) if topo else 1
    transient = next(n["id"] for n in topo["nodes"] if n["kind"] == 1 and n["mode"] != 0) if topo else 0
    addresses = [base + i * 0x8000 for i in range(8)]
    requests = [row for row in fired if row["direction"] == "cchi_rx_req"]
    expected_requests = [(coherent if i == 0 else transient, 20 + i, 16 if i == 0 else 3,
                          addresses[i] if i < 8 else addresses[0 if i == 8 else 5]) for i in range(10)]
    assert [(r["node"], r["txn_id"], r["opcode"], r["address"]) for r in requests] == expected_requests
    lower = [r for r in fired if r["direction"] == "chi_tx_req" and (r["address"] & 0x7fff) == (base & 0x7fff)]
    reads = [r for r in lower if r["opcode"] in (7, 0x26)]
    assert [(r["opcode"], r["address"]) for r in reads] == [(7, addresses[0])] + [
        (0x26, a) for a in addresses[1:] + [addresses[0]]]
    victims = [r for r in lower if r["opcode"] in (0x1b, 0x42)]
    assert [(r["opcode"], r["address"]) for r in victims] == [(0x1b, addresses[0])] + [
        (0x42, a) for a in addresses[1:5]]
    assert len(lower) == 14
    branch_rows = []
    dirty = bytearray(((addresses[0] >> 6) ^ (i * 17) ^ seed) & 255 for i in range(64))
    dirty[0] ^= 0xa5
    dirty[63] ^= 0x5a
    for index, victim in enumerate(victims):
        end = victims[index + 1]["cycle"] if index + 1 < 5 else float("inf")
        replies = [r for r in fired if r["direction"] == "chi_rx_rsp" and
                   r["txn_id"] == victim["txn_id"] and victim["cycle"] < r["cycle"] < end]
        # No Retry is generated by this fixed profile. Reads use CompData, so
        # their acquisition role sharing this TxnID cannot supply these replies.
        assert len(replies) == 1
        reply = replies[0]
        copyback_branch = index in (0, 2, 4)
        assert reply["opcode"] == (5 if copyback_branch else 4)
        identity = reply["node"], reply["dbid"]
        ack = [r for r in fired if r["direction"] == "chi_tx_rsp" and
               (r["target"], r["txn_id"]) == identity]
        data = [r for r in fired if r["direction"] == "chi_tx_dat" and
                (r["target"], r["txn_id"]) == identity]
        if copyback_branch:
            assert not ack and len(data) == 2
            assert {r["data_id"] for r in data} == {0, 2}
            expected = dirty if index == 0 else bytes(((victim["address"] >> 6) ^ (i * 17) ^ seed) & 255 for i in range(64))
            for row in data:
                assert row["cycle"] > reply["cycle"] and row["opcode"] == 2
                assert row["resp"] == (6 if index == 0 else 1)
                assert row["trace_tag"] == reply["trace_tag"] and row["resp_err"] == 0
                assert row["byte_enable"] == 0xffffffff
                beat = row["data_id"] // 2
                assert bytes.fromhex(row["data"]) == expected[beat * 32:(beat + 1) * 32]
        else:
            assert not data and len(ack) == 1
            assert ack[0]["opcode"] == 2 and ack[0]["trace_tag"] == reply["trace_tag"]
            assert ack[0]["cycle"] > reply["cycle"]
        branch_rows.append({"address": victim["address"], "opcode": victim["opcode"],
                            "branch": "CompDBIDResp" if copyback_branch else "Comp",
                            "copybackBeats": len(data), "compAcks": len(ack)})
    snoops = [r for r in fired if r["direction"] == "cchi_tx_snp"]
    assert len(snoops) == 1 and snoops[0]["address"] == addresses[0] and snoops[0]["opcode"] == 1
    returned = [r for r in fired if r["direction"] == "cchi_rx_dat"]
    assert len(returned) == 2 and {r["data_id"] for r in returned} == {0, 1}
    for row in returned:
        assert row["opcode"] == 3 and row["resp"] == 4 and row["node"] == coherent
        assert row["txn_id"] == snoops[0]["txn_id"] and row["trace_tag"] == snoops[0]["trace_tag"]
        beat = row["data_id"]
        assert bytes.fromhex(row["data"]) == dirty[beat * 32:(beat + 1) * 32]
    return {"primaryVictims": branch_rows, "dirtyClientRecallBeats": len(returned),
            "residentHitAddress": addresses[5], "dirtyMemoryReadbackAddress": addresses[0]}


def mutations(events, seed, topo=None):
    check(events, seed, topo)
    def corrupt_data(rows):
        row = next(r for r in rows if r["handshake"] and r["direction"] == "chi_tx_dat" and r["opcode"] == 2)
        row["data"] = f"{int(row['data'][:2], 16) ^ 1:02x}" + row["data"][2:]
    def wrong_victim(rows):
        row = next(r for r in rows if r["handshake"] and r["direction"] == "chi_tx_req" and r["opcode"] == 0x1b)
        row["address"] += 0x8000
    def dirty_as_clean(rows):
        row = next(r for r in rows if r["handshake"] and r["direction"] == "chi_tx_req" and r["opcode"] == 0x1b)
        row["opcode"] = 0x42
    def drop_dirty(rows):
        row = next(r for r in rows if r["handshake"] and r["direction"] == "chi_tx_dat" and r["resp"] == 6)
        row["resp"] = 2
    def partial_bytes(rows):
        row = next(r for r in rows if r["handshake"] and r["direction"] == "chi_tx_dat" and r["opcode"] == 2)
        row["byte_enable"] = 1
    def lose_recall(rows):
        row = next(r for r in rows if r["handshake"] and r["direction"] == "cchi_rx_dat")
        rows.remove(row)
    def duplicate_copyback(rows):
        row = next(r for r in rows if r["handshake"] and r["direction"] == "chi_tx_dat" and r["opcode"] == 2)
        rows.append(deepcopy(row))
    def wrong_dbid(rows):
        row = next(r for r in rows if r["handshake"] and r["direction"] == "chi_tx_dat" and r["opcode"] == 2)
        row["txn_id"] += 1
    actions = [corrupt_data, wrong_victim, dirty_as_clean, drop_dirty, partial_bytes,
               lose_recall, duplicate_copyback, wrong_dbid]
    for action in actions:
        copied = deepcopy(events)
        action(copied)
        try:
            check(copied, seed, topo)
        except (AssertionError, KeyError):
            continue
        raise AssertionError("victim checker accepted mutation: " + action.__name__)
    return len(actions)


if __name__ == "__main__":
    root = Path(sys.argv[1])
    rows = [json.loads(line) for line in (root / "canonical.jsonl").read_text().splitlines()]
    topo = json.loads((root / "topology.json").read_text()) if (root / "topology.json").exists() else None
    count = mutations(rows[1:], rows[0]["seed"], topo)
    print(f"independent victim trace checker rejected {count} invalid observations")
